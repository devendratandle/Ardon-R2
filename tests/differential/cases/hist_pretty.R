# hist(plot = FALSE) — R's histogram object: Sturges breaks through
# pretty(), counts with right-closed bins and a closed lowest break,
# density, mids — and the two functions it is built on.
p <- function(k, v) cat(k, "=", paste(sprintf("%.15g", v), collapse = ","), "\n", sep = "")
x <- c(81.5, 77, 92.25, 68, 88, 95.5, 73, 61, 84, 79.5, 90, 70.25)
h <- hist(x, plot = FALSE)
p("h.breaks", h$breaks)
p("h.counts", h$counts)
p("h.density", h$density)
p("h.mids", h$mids)
cat("h.equidist=", h$equidist, "\n", sep = "")
h4 <- hist(x, breaks = 4, plot = FALSE)
p("h4.breaks", h4$breaks)
p("h4.counts", h4$counts)
hv <- hist(x, breaks = c(60, 70, 75, 90, 100), plot = FALSE)
p("hv.counts", hv$counts)
p("hv.density", hv$density)
# a value exactly on a break goes to the bin on its left
he <- hist(c(0, 1, 1, 2, 2, 3, 5), breaks = 0:5, plot = FALSE)
p("he.counts", he$counts)
z <- c(-2.21, -0.84, -0.33, -0.12, 0.05, 0.18, 0.39, 0.49, 0.58, 0.74, 0.92, 1.12, 1.51, 1.59, 2.4)
hz <- hist(z, plot = FALSE)
p("hz.breaks", hz$breaks)
p("hz.counts", hz$counts)
p("pretty.1", pretty(c(61, 95.5)))
p("pretty.2", pretty(c(0, 1)))
p("pretty.3", pretty(c(-3.7, 12.2)))
p("pretty.4", pretty(c(0.001234, 0.0457), n = 7))
p("pretty.5", pretty(1e6 + c(0, 3)))
p("pretty.6", pretty(c(5, 5)))
p("pretty.7", pretty(c(-1e-3, 2e-3), n = 3))
p("pretty.8", pretty(c(1, 1000), n = 10))
p("pretty.9", pretty(c(0.7, 23.1), n = 4))
p("pretty.10", pretty(c(-50, -1)))
p("sturges.12", nclass.Sturges(x))
p("sturges.100", nclass.Sturges(1:100))
p("sturges.1", nclass.Sturges(3))
