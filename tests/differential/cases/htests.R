# Hypothesis tests on fixed data: statistic, df, p-value, CI.
# Values print with 15 significant digits so the harness's 1e-9 relative
# tolerance is what is actually tested (cat() alone prints 7).
p <- function(k, v) cat(k, "=", sprintf("%.15g", v), "\n", sep = "")
x <- c(5.1, 4.9, 6.2, 5.8, 6.0, 5.5, 5.3, 6.4, 4.7, 5.9)
y <- c(6.3, 5.8, 7.1, 6.0, 6.8, 6.6, 5.9, 7.4, 6.1, 6.9)
z <- c(4.2, 5.0, 3.9, 4.8, 5.2, 4.4)
t1 <- t.test(x, mu = 5)
p("t1.stat", t1$statistic)
p("t1.df", t1$parameter)
p("t1.p", t1$p.value)
p("t1.lo", t1$conf.int[1])
p("t1.hi", t1$conf.int[2])
tw <- t.test(x, z)
p("welch.stat", tw$statistic)
p("welch.df", tw$parameter)
p("welch.p", tw$p.value)
p("welch.lo", tw$conf.int[1])
tp <- t.test(x, z, var.equal = TRUE)
p("pooled.stat", tp$statistic)
p("pooled.df", tp$parameter)
p("pooled.p", tp$p.value)
tpr <- t.test(x, y, paired = TRUE)
p("paired.stat", tpr$statistic)
p("paired.df", tpr$parameter)
p("paired.p", tpr$p.value)
p("paired.hi", tpr$conf.int[2])
t9 <- t.test(x, mu = 5, conf.level = 0.9)
p("t90.lo", t9$conf.int[1])
df <- data.frame(v = c(x, z), g = c(rep("a", 10), rep("b", 6)))
tf <- t.test(v ~ g, data = df)
p("formula.stat", tf$statistic)
p("formula.p", tf$p.value)
m <- matrix(c(12, 5, 7, 9), nrow = 2)
c1 <- chisq.test(m)
p("chi.yates.stat", c1$statistic)
p("chi.yates.p", c1$p.value)
c2 <- chisq.test(m, correct = FALSE)
p("chi.raw.stat", c2$statistic)
p("chi.raw.p", c2$p.value)
m3 <- matrix(c(10, 20, 30, 15, 25, 12), nrow = 2)
c3 <- chisq.test(m3)
p("chi.2x3.stat", c3$statistic)
p("chi.2x3.df", c3$parameter)
p("chi.2x3.p", c3$p.value)
c4 <- chisq.test(c(18, 22, 30, 30))
p("chi.gof.stat", c4$statistic)
p("chi.gof.p", c4$p.value)
c5 <- chisq.test(c(18, 22, 30, 30), p = c(0.1, 0.2, 0.3, 0.4))
p("chi.gofp.stat", c5$statistic)
p("chi.gofp.p", c5$p.value)
tm <- t.test(x, z, mu = 0.5)
p("welch.mu.stat", tm$statistic)
p("welch.mu.p", tm$p.value)
p("welch.mu.lo", tm$conf.int[1])
tpm <- t.test(x, z, var.equal = TRUE, mu = 0.5)
p("pooled.mu.stat", tpm$statistic)
p("pooled.mu.p", tpm$p.value)
p("pooled.lo", tp$conf.int[1])
p("pooled.hi", tp$conf.int[2])
tfp <- t.test(v ~ g, data = df, var.equal = TRUE)
p("formula.pooled.stat", tfp$statistic)
p("formula.pooled.df", tfp$parameter)
c6 <- chisq.test(m3, correct = TRUE)
p("chi.2x3.correctarg.stat", c6$statistic)
m4 <- matrix(c(20, 15, 30, 35, 25, 40, 10, 5, 20), nrow = 3)
c7 <- chisq.test(m4)
p("chi.3x3.stat", c7$statistic)
p("chi.3x3.df", c7$parameter)
p("chi.3x3.p", c7$p.value)
# table(a, b) is a two-way table: independence, not one row of counts
ta <- rep(c("lo", "mid", "hi"), times = c(14, 11, 15))
tb <- rep(c("no", "yes", "no", "yes", "no", "yes"), times = c(10, 4, 3, 8, 6, 9))
c8 <- chisq.test(table(ta, tb))
p("chi.tab.stat", c8$statistic)
p("chi.tab.df", c8$parameter)
p("chi.tab.p", c8$p.value)
c9 <- chisq.test(ta, tb)
p("chi.xy.stat", c9$statistic)
p("chi.xy.p", c9$p.value)
c10 <- chisq.test(table(ta == "lo", tb))
p("chi.tab22.stat", c10$statistic)
p("chi.tab22.p", c10$p.value)
fa <- factor(c(ta, NA), levels = c("lo", "mid", "hi", "unused"))
c11 <- chisq.test(fa, c(tb, "no"))
p("chi.xyna.stat", c11$statistic)
p("chi.xyna.df", c11$parameter)
c12 <- chisq.test(matrix(c(18, 22, 30, 30), nrow = 1))
p("chi.row.stat", c12$statistic)
p("chi.row.df", c12$parameter)
